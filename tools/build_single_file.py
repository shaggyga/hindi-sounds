def embedded_files(root: Path):
    for directory in ('assets', 'licenses'):
        for path in sorted((root / directory).rglob('*')):
            if path.is_file():
                yield path.relative_to(root).as_posix(), path
    yield 'THIRD_PARTY_NOTICES.md', root / 'THIRD_PARTY_NOTICES.md'


def asset_archive(root: Path) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', compression=zipfile.ZIP_DEFLATED,
                         compresslevel=9) as archive:
        for name, path in embedded_files(root):
            info = zipfile.ZipInfo(name, (2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, path.read_bytes(), compresslevel=9)
    return buffer.getvalue()


def flatten_module(root: Path, name: str) -> str:
    source = (root / 'hindi_sounds' / f'{name}.py').read_text(encoding='utf-8-sig')
    lines = source.splitlines(keepends=True)
    replacements = []
    for node in ast.parse(source).body:
        replacement = None
        if isinstance(node, ast.ImportFrom) and (node.level or node.module == '__future__'):
            replacement = ''
        elif isinstance(node, ast.FunctionDef) and name == 'settings' and node.name == 'asset_root':
            replacement = ("def asset_root() -> Path:\n"
                           "    if _hs_asset_directory is None:\n"
                           "        raise RuntimeError('Embedded assets have not been unpacked')\n"
                           "    return _hs_asset_directory\n")
        elif isinstance(node, ast.If) and ast.unparse(node.test) == "__name__ == '__main__'":
            replacement = ''
        if replacement is not None:
            replacements.append((node.lineno - 1, node.end_lineno, replacement))
    for start, end, replacement in reversed(replacements):
        lines[start:end] = [replacement]
    result = ''.join(lines).strip()
    # main.run imports MainWindow inside its startup handler. It is already
    # defined above in this edition; remove that nested relative import too.
    result = result.replace('        from .window import MainWindow\n', '')
    if name == 'window':
        result = result.replace(
            'See THIRD_PARTY_NOTICES.md in the app folder for details.',
            'Credits and license texts are embedded in this script.\\n'
            'Run with --extract-assets FOLDER to save them.')
    if name == 'main':
        original = "    QFontDatabase.addApplicationFont(str(asset_root()/'fonts'/'hindi.ttf'))"
        if result.count(original) != 1:
            raise ValueError('Font initialization changed; update the single-file builder')
        result = result.replace(original, "    _hs_font_ids.append(QFontDatabase.addApplicationFont(str(asset_root()/'fonts'/'hindi.ttf')))")
        result = result.replace(
            "    parser.add_argument('--windowed',action='store_true')",
            "    parser.add_argument('--extract-assets',type=Path,help='Save embedded recordings, font, and license texts')\n"
            "    parser.add_argument('--windowed',action='store_true')")
    if any(isinstance(node, ast.ImportFrom) and node.level for node in ast.walk(ast.parse(result))):
        raise ValueError(f'Unresolved relative import in {name}')
    return f'# ===== {name}.py =====\n{result}\n\n'


def render(root: Path = ROOT) -> str:
    archive = asset_archive(root)
    encoded = _wrapped_payload(archive)
    code = HEADER + ''.join(flatten_module(root, name) for name in MODULES)
    code += '# ===== Embedded recordings, font, icon, and full notices =====\n'
    code += f'_hs_payload_sha256 = {hashlib.sha256(archive).hexdigest()!r}\n'
    code += '_hs_payload = b"""\n' + encoded + '\n"""\n'
    code += FOOTER
    compile(code, 'HindiSounds_Standalone.py', 'exec')
    return code


def _wrapped_payload(payload: bytes) -> str:
    encoded = base64.b85encode(payload).decode('ascii')
    return '\n'.join(encoded[offset:offset + 120]
                     for offset in range(0, len(encoded), 120))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'HindiSounds_Standalone.py')
    args = parser.parse_args()
    source = render()
    args.output.write_text(source, encoding='utf-8', newline='\n')
    print(f'{args.output.name}: {args.output.stat().st_size:,} bytes; 46 recordings embedded')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
