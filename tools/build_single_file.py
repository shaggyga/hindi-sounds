"""Build the downloadable, self-contained Python source version of Hindi Sounds.

The resulting script has readable application code and an embedded asset ZIP.
Only the Python standard library is needed to build it.
"""
from __future__ import annotations

import argparse
import ast
import base64
import hashlib
import io
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
MODULES = ('settings', 'controller', 'player', 'theme', 'window', 'main')

